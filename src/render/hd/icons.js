const urls = new Map();
export function iconUrl(id) {
  if (!urls.has(id)) {
    const lay = ART[id];
    urls.set(id, lay ? compose([lay], {}, 16, 16).toDataURL() : null);
  }
  return urls.get(id);
}
export const ICON_IDS = Object.keys(ART);
