export const GLYPH_HEIGHT = 7;
export const LINE_HEIGHT = 8;

// Lowercase: squat capitals (5 rows) drawn on the baseline.
const SMALL = {};
for (const ch of 'ABCDEFGHIJKLMNOPQRSTUVWXYZ') {
  const g = RAW[ch];
  // Take rows 0,2,3,5,6 of the capital to make a shorter letter.
  SMALL[ch.toLowerCase()] = ['.....', '.....', g[0], g[2], g[3], g[5], g[6]].map((r) => r.padEnd(5, '.').slice(0, g[0].length));
}
const GLYPHS = { ...RAW, ...SMALL };

export function glyph(ch) { return GLYPHS[ch] || GLYPHS[ch.toUpperCase()] || RAW['?']; }
export function fontHas(ch) { return !!(GLYPHS[ch] || GLYPHS[ch.toUpperCase()]); }
export function glyphWidth(ch) { return glyph(ch)[0].length; }

// Width in pixels of a string (1px gap between glyphs).
export function measureText(text) {
  let w = 0;
  for (const ch of text) w += glyphWidth(ch) + 1;
  return Math.max(0, w - 1);
}

// Draw text at (x, y) = top-left, in colour. Returns the width drawn.
export function drawText(ctx, text, x, y, colour) {
  ctx.fillStyle = colour;
  let cx = x;
  for (const ch of text) {
    const g = glyph(ch);
    for (let row = 0; row < g.length; row++) {
      const line = g[row];
      for (let col = 0; col < line.length; col++) {
        if (line[col] === '#') ctx.fillRect(cx + col, y + row, 1, 1);
      }
    }
    cx += g[0].length + 1;
  }
  return cx - x - 1;
}

// Draw text centred on cx.
export function drawTextCentred(ctx, text, cx, y, colour) {
  return drawText(ctx, text, Math.round(cx - measureText(text) / 2), y, colour);
}
